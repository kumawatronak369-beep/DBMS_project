from datetime import datetime

from sqlalchemy import Computed, DateTime, Enum, Index, String, UniqueConstraint, func, text
from sqlalchemy.dialects.mysql import BIGINT
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class Destination(Base):
    __tablename__ = "destinations"
    __table_args__ = (
        UniqueConstraint("ip_address", "domain_key", name="uq_destinations_ip_domain"),
        Index("idx_destinations_domain", "domain"),
        Index("idx_destinations_category", "category"),
        Index("idx_destinations_last_seen", "last_seen"),
    )

    destination_id: Mapped[int] = mapped_column(BIGINT(unsigned=True), primary_key=True, autoincrement=True)
    ip_address: Mapped[str] = mapped_column(String(45))
    domain: Mapped[str | None] = mapped_column(String(255), nullable=True)
    # generated by MySQL as COALESCE(domain, ''); never written to
    domain_key: Mapped[str | None] = mapped_column(String(255), Computed("COALESCE(domain, '')", persisted=True))
    category: Mapped[str] = mapped_column(
        Enum(
            "SEARCH", "SOCIAL", "DEVELOPMENT", "EDUCATION", "VIDEO", "CLOUD", "OTHER", "UNKNOWN",
            name="destination_category",
        ),
        server_default="UNKNOWN",
    )
    first_seen: Mapped[datetime] = mapped_column(DateTime, server_default=func.current_timestamp())
    last_seen: Mapped[datetime] = mapped_column(DateTime, server_default=func.current_timestamp())
    created_at: Mapped[datetime] = mapped_column(DateTime, server_default=func.current_timestamp())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime,
        server_default=text("CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP"),
        server_onupdate=text("CURRENT_TIMESTAMP"),
    )
