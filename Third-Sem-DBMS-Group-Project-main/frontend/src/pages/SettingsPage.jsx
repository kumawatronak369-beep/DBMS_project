import { FlaskConical, Info, LogOut, ShieldCheck, UserCircle } from 'lucide-react'
import { HealthList } from '../components/HealthIndicators.jsx'
import { Button } from '../components/ui/Button.jsx'
import { Card, CardBody, CardHeader } from '../components/ui/Card.jsx'
import { DetailList, PageHeader } from '../components/ui/Misc.jsx'
import { StatusBadge } from '../components/ui/StatusBadge.jsx'
import { useAuth } from '../hooks/useAuth.js'
import { useHealth } from '../hooks/useHealth.js'
import { formatDateTime, relativeTime } from '../utils/format.js'

const PERMISSIONS = {
  ADMIN: 'Everything an analyst can do, plus adding, editing and disabling nodes, and managing users.',
  ANALYST: 'View the dashboard, nodes, devices, destinations and network history, and generate reports.',
}

export default function SettingsPage() {
  const { user, expiresAt, logout } = useAuth()
  const health = useHealth()

  return (
    <>
      <PageHeader title="Settings" subtitle="Your account and system information" />

      <div className="grid grid-cols-1 gap-4 lg:grid-cols-2">
        <Card>
          <CardHeader title="Account" icon={UserCircle} />
          <CardBody>
            <DetailList
              items={[
                { label: 'Name', value: user?.name },
                { label: 'Email', value: user?.email, mono: true },
                { label: 'Role', value: <StatusBadge status={user?.role} /> },
                { label: 'Status', value: <StatusBadge status={user?.status} /> },
                { label: 'Last sign-in', value: formatDateTime(user?.last_login) },
                { label: 'Session ends', value: expiresAt ? `${formatDateTime(expiresAt)} (${relativeTime(expiresAt)})` : '—' },
              ]}
            />
            <p className="mt-4 text-xs text-muted">{PERMISSIONS[user?.role]}</p>
            <div className="mt-4">
              <Button icon={LogOut} onClick={logout}>
                Sign out
              </Button>
            </div>
          </CardBody>
        </Card>

        <Card>
          <CardHeader title="System status" icon={ShieldCheck} />
          <div className="px-4 py-1">
            <HealthList health={health} />
          </div>
        </Card>

        <Card className="lg:col-span-2">
          <CardHeader title="About this system" icon={Info} />
          <CardBody className="space-y-3 text-[13px] text-ink/90">
            <p>
              NetMonitor records network <strong>metadata only</strong>: which device reached which destination, and
              when. It never captures passwords, message content or packet payloads, and is intended only for networks
              you are authorized to monitor.
            </p>
            <p>
              <strong>30-second de-duplication.</strong> When the same device reaches the same destination again within
              30 seconds of a stored event, the repeat is not stored. The same event after more than 30 seconds is
              stored. This keeps history meaningful without noise from repeated requests.
            </p>
            <p>
              Collectors authenticate with a per-node API key. The node is always taken from that key, never from the
              submitted data.
            </p>
            <p className="flex items-start gap-2 rounded-md border border-warn/30 bg-warn/10 px-3 py-2 text-xs text-warn">
              <FlaskConical size={14} className="mt-px shrink-0" aria-hidden="true" />
              Demonstration environment: network events shown here are generated by a simulated collector, not
              captured from a real network.
            </p>
          </CardBody>
        </Card>
      </div>
    </>
  )
}
