import { screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import { ADMIN, ANALYST } from '../test/fixtures.js'
import { SESSION_KEY, renderApp } from '../test/render.jsx'

describe('SettingsPage', () => {
  it('shows the signed-in account and what its role may do', async () => {
    renderApp('/settings', { user: ANALYST })
    const account = (await screen.findByRole('heading', { name: 'Account' })).closest('section')
    expect(within(account).getByText('Network Analyst')).toBeInTheDocument()
    expect(within(account).getByText('analyst@netmonitor.local')).toBeInTheDocument()
    expect(within(account).getByText('Analyst')).toBeInTheDocument()
    expect(within(account).getByText(/View the dashboard/)).toBeInTheDocument()
  })

  it('describes the admin role differently', async () => {
    renderApp('/settings', { user: ADMIN })
    expect(await screen.findByText(/managing users/)).toBeInTheDocument()
  })

  it('states the system scope and the 30-second rule', async () => {
    renderApp('/settings')
    expect(await screen.findByText(/metadata only/)).toBeInTheDocument()
    expect(screen.getByText(/30-second de-duplication/)).toBeInTheDocument()
    expect(screen.getByText(/generated by a simulated collector/)).toBeInTheDocument()
  })

  it('signs out, clears the stored session and returns to login', async () => {
    const { api } = renderApp('/settings', { routes: { 'POST /api/auth/logout': { message: 'ok' } } })
    await userEvent.click(await screen.findByRole('button', { name: 'Sign out' }))
    expect(await screen.findByRole('button', { name: /sign in/i })).toBeInTheDocument()
    expect(api.callsTo('POST /api/auth/logout')).toHaveLength(1)
    await waitFor(() => expect(localStorage.getItem(SESSION_KEY)).toBeNull())
  })
})
